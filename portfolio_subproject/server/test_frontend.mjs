import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const load = async path => import('data:text/javascript;base64,' + Buffer.from(ts.transpileModule(await readFile(new URL(path, import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText).toString('base64'));
const { ReadRequestCache } = await load('../content/requestCache.ts');
const { commitReference, commitCover, addSection, moveItem } = await load('../editor/draftOperations.ts');
let count = 0, resolveA;
const cache = new ReadRequestCache(30000, 2);
const pending = () => { count++; return new Promise(resolve => { resolveA = resolve; }); };
const a = cache.read('a', 'root', pending);
const duplicate = cache.read('a', 'root', pending, true);
assert.equal(a, duplicate); assert.equal(count, 1);
resolveA({ items: ['a'] }); await a;
assert.deepEqual(await cache.read('a', 'root', pending), { items: ['a'] }); assert.equal(count, 1);
assert.deepEqual(await cache.read('b', 'root', async () => ({ items: ['b'] })), { items: ['b'] });
let oldResolve;
const old = cache.read('old', 'item', () => new Promise(resolve => { oldResolve = resolve; }));
await cache.read('new', 'item', async () => 'new'); oldResolve('old'); await old;
assert.equal(await cache.read('new', 'item', async () => 'wrong'), 'new');
await assert.rejects(cache.read('new', 'failure', async () => { throw Error('offline'); }));
assert.equal(await cache.read('new', 'failure', async () => 'retry'), 'retry');
const expiring = new ReadRequestCache(-1); await expiring.read('a','x',async()=>1); assert.equal(await expiring.read('a','x',async()=>2),2);
await cache.read('new','refresh',async()=>1); assert.equal(await cache.read('new','refresh',async()=>2,true),2);
const draft = { sections: [{ id: 'one', title: 'A', layout: 'grid', blocks: [] }] };
const other = addSection(draft), original = JSON.stringify(draft);
const selected = { title: '图片', type: 'image', ref: { source: 'share', id: 'share1', part: 'image', key: 'stable' } };
assert.equal(JSON.stringify(draft), original); // preview/cancel has no mutation API
const block = commitReference(draft, 'one', undefined, selected);
assert.equal(draft.sections[0].blocks.length,1); assert.equal(other.blocks.length,0);
block.span = 2;
const replacement = commitReference(draft,'one',block.id,{...selected,title:'替换'});
assert.equal(replacement.id,block.id); assert.equal(replacement.span,2); assert.equal(draft.sections[0].blocks.length,1);
assert.throws(()=>commitReference(draft,'deleted',undefined,selected));
assert.throws(()=>commitReference(draft,'one','deleted',selected));
const order=['a','b'];moveItem(order,0,-1);assert.deepEqual(order,['a','b']);moveItem(order,0,1);assert.deepEqual(order,['b','a']);
const previousText = replacement.text; commitCover(draft, 'one', replacement.id, {...selected, url:'https://example.com/cover.gif'}); assert.equal(replacement.cover_url,'https://example.com/cover.gif'); assert.equal(replacement.text,previousText); assert.throws(()=>commitCover(draft,'one',replacement.id,{...selected,type:'file'}));
console.log('PASS: request coalescing, refresh, TTL, account isolation, stale completions, retry, stable draft targets, replacement and ordering');
